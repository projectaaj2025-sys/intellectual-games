// Run with: node tests/show-formats.test.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
const start = html.indexOf('const NB_TEXT =');
const end = html.indexOf('function initNativeBuilder()', start);
assert(start >= 0 && end > start);
const c = vm.createContext({ S:{lang:'ru'}, renderNativeBuilder:()=>{} });
vm.runInContext(html.slice(start,end)+'\nglobalThis.samples = SHOW_DEMOS;', c);
assert.equal(c.samples.length,3);
for (const game of c.samples) assert(c.nativeValid(game),game.showFormat);
const copy = x => JSON.parse(JSON.stringify(x));
const millionaire = copy(c.samples.find(x=>x.showFormat==='million'));
assert.equal(millionaire.showItems.length,15);
millionaire.showItems[0].options[1]=millionaire.showItems[0].options[0];
assert.equal(c.nativeValid(millionaire),false);
const survey = copy(c.samples.find(x=>x.showFormat==='hundred'));
assert.equal(survey.showItems.length,6);
survey.showItems[0].answers[0].points='';
assert.equal(c.nativeValid(survey),false);
survey.showItems[0].answers[0].points=99;
assert.equal(c.nativeValid(survey),false);
const chgk=copy(c.samples.find(x=>x.showFormat==='chgk'));
assert.equal(chgk.showItems.length,13);
chgk.showItems[0]={kind:'blitz',blitz:[{q:'Q1',a:'A1'},{q:'Q2',a:'A2'},{q:'Q3',a:'A3'}]};
assert.equal(c.nativeValid(chgk),true);
chgk.showItems[0].blitz[1].a='';
assert.equal(c.nativeValid(chgk),false);
console.log('Native show data and validation: OK');
